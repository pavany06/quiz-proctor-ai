# 5. PROCTORING & ANOMALY DETECTION: STATISTICAL Z-SCORE ENGINE
# ==============================================================================
class ProctoringAnomalyDetector:
    """
    Statistical anomaly detector for online proctoring:
    Flags suspicious exam attempts using Z-score outlier detection and heuristic metrics
    (e.g., abnormally fast response times, high tab-switch counts, irregular score spikes).
    """
    @staticmethod
    def calculate_z_score(value: float, mean: float, std_dev: float) -> float:
        if std_dev == 0:
            return 0.0
        return (value - mean) / std_dev

    def analyze_attempt(
        self,
        time_spent_sec: float,
        expected_time_sec: float,
        tab_switches: int,
        score_pct: float,
        peer_avg_time_sec: float = 1200.0,
        peer_time_std_dev: float = 300.0
    ) -> Dict[str, Any]:
        """
        Calculates integrity confidence score and anomaly flags.
        """
        flags = []
        time_z = self.calculate_z_score(time_spent_sec, peer_avg_time_sec, peer_time_std_dev)

        # Flag 1: Impossibly rapid test completion with high accuracy
        if time_spent_sec < (expected_time_sec * 0.25) and score_pct > 85.0:
            flags.append("ANOMALOUS_SPEED: Perfect/near-perfect score in <25% of allotted duration.")

        # Flag 2: Excessive tab switching / window defocus
        if tab_switches >= 3:
            flags.append(f"TAB_SWITCH_VIOLATION: User defocused or switched browser window {tab_switches} times.")

        # Integrity confidence score calculation (0 to 100)
        penalty = (tab_switches * 15) + (30 if abs(time_z) > 2.5 and score_pct > 90 else 0)
        trust_score = max(0, min(100, 100 - penalty))

        return {
            "integrityScore": trust_score,
            "isFlagged": len(flags) > 0,
            "anomalyFlags": flags,
            "timeZScore": round(time_z, 2),
            "recommendation": "Manual Review Required" if trust_score < 70 else "Verified Normal Submission"
        }


