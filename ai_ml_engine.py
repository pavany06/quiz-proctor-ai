# 4. ADAPTIVE TESTING ENGINE: BAYESIAN KNOWLEDGE TRACING & IRT
# ==============================================================================
class AdaptiveDifficultyEngine:
    """
    Implements 1-Parameter Logistic Item Response Theory (Rasch Model) & Bayesian Updating:
    P(Correct | Ability, Difficulty) = 1 / (1 + exp(-(theta - beta)))
    Dynamically routes Easy, Medium, or Hard questions based on running student ability theta.
    """
    def __init__(self, prior_ability: float = 0.0):
        self.theta = prior_ability  # Ability estimate in range [-3.0, +3.0]
        self.difficulty_map = {"Easy": -1.0, "Medium": 0.0, "Hard": 1.2}

    def probability_correct(self, difficulty_str: str) -> float:
        beta = self.difficulty_map.get(difficulty_str, 0.0)
        return 1.0 / (1.0 + math.exp(-(self.theta - beta)))

    def update_ability_after_response(self, difficulty_str: str, is_correct: bool, time_spent_sec: float) -> None:
        """
        Updates student theta using stochastic gradient step based on prediction error.
        """
        p = self.probability_correct(difficulty_str)
        outcome = 1.0 if is_correct else 0.0
        error = outcome - p
        
        # Adaptive step size (learning rate)
        alpha = 0.4
        self.theta += alpha * error

    def get_next_recommended_difficulty(self) -> str:
        """
        Selects the next question difficulty targeting the student's Zone of Proximal Development.
        """
        if self.theta >= 0.8:
            return "Hard"
        elif self.theta >= -0.3:
            return "Medium"
        else:
            return "Easy"


