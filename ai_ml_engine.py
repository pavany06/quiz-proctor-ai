# 2. SUPERVISED LEARNING: LOGISTIC REGRESSION (STUDENT PASS/RISK PREDICTOR)
# ==============================================================================
class StudentRiskPredictor:
    """
    Binary Classification model predicting whether a student is at-risk of failing 
    an upcoming exam based on historical test scores, completion speed, and practice rate.
    """
    def __init__(self, learning_rate: float = 0.05, epochs: int = 1000):
        self.lr = learning_rate
        self.epochs = epochs
        self.weights: Optional[np.ndarray] = None
        self.bias: float = 0.0

    @staticmethod
    def _sigmoid(z: np.ndarray) -> np.ndarray:
        return 1.0 / (1.0 + np.exp(-np.clip(z, -25.0, 25.0)))

    def train(self, X: np.ndarray, y: np.ndarray) -> None:
        """
        Trains Logistic Regression weights using Gradient Descent.
        Features in X: [Avg_Past_Score_Pct, Time_Spent_Ratio, Completion_Rate]
        Target in y: 1 (Pass) or 0 (At-Risk)
        """
        num_samples, num_features = X.shape
        self.weights = np.zeros(num_features)
        self.bias = 0.0

        for _ in range(self.epochs):
            linear_model = np.dot(X, self.weights) + self.bias
            y_pred = self._sigmoid(linear_model)

            # Gradient calculation
            dw = (1 / num_samples) * np.dot(X.T, (y_pred - y))
            db = (1 / num_samples) * np.sum(y_pred - y)

            # Weight update
            self.weights -= self.lr * dw
            self.bias -= self.lr * db

    def predict_risk(self, student_features: List[float]) -> Dict[str, Any]:
        """
        Predicts the pass probability and returns risk classification.
        """
        if self.weights is None:
            # Fallback initialized weights if not trained on live dataset
            self.weights = np.array([0.045, 0.025, 0.030])
            self.bias = -3.2

        x = np.array(student_features)
        z = np.dot(x, self.weights) + self.bias
        pass_prob = float(self._sigmoid(np.array([z]))[0])
        fail_prob = 1.0 - pass_prob

        status = "Safe / High Probability" if pass_prob >= 0.70 else ("Moderate Risk" if pass_prob >= 0.40 else "High Risk")

        return {
            "passProbability": round(pass_prob * 100, 2),
            "riskProbability": round(fail_prob * 100, 2),
            "riskCategory": status,
            "interventionRecommended": pass_prob < 0.50
        }


