# 3. UNSUPERVISED LEARNING: K-MEANS CLUSTERING (STUDENT SEGMENTATION)
# ==============================================================================
class StudentCohortClusterer:
    """
    Clusters students into 3 cohorts (Top Achievers, Steady Performers, Needing Support)
    using K-Means Clustering on multi-dimensional performance metrics.
    """
    def __init__(self, k: int = 3, max_iters: int = 100):
        self.k = k
        self.max_iters = max_iters
        self.centroids: Optional[np.ndarray] = None

    def fit_predict(self, data_points: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
        """
        Runs Lloyd's K-Means clustering algorithm.
        Dimensions: [Score_Percentage, Accuracy_Rate, Avg_Response_Time_Sec]
        """
        n_samples = data_points.shape[0]
        # Random initial centroids
        np.random.seed(42)
        random_indices = np.random.choice(n_samples, self.k, replace=False)
        self.centroids = data_points[random_indices]

        labels = np.zeros(n_samples)

        for _ in range(self.max_iters):
            # Compute Euclidean distances to all centroids
            distances = np.linalg.norm(data_points[:, np.newaxis] - self.centroids, axis=2)
            new_labels = np.argmin(distances, axis=1)

            # Check convergence
            if np.array_equal(labels, new_labels):
                break
            labels = new_labels

            # Re-calculate centroids
            for cluster_idx in range(self.k):
                cluster_members = data_points[labels == cluster_idx]
                if len(cluster_members) > 0:
                    self.centroids[cluster_idx] = cluster_members.mean(axis=0)

        return labels, self.centroids

    @staticmethod
    def get_cluster_name(cluster_idx: int) -> str:
        names = {
            0: "High Performers (Advanced Concepts)",
            1: "Consistent Learners (Standard Track)",
            2: "Remedial Support Required (Foundations)"
        }
        return names.get(cluster_idx, "General Cluster")


